-- ACT setup for Snowflake: a service user that trusts Domino through workload identity federation.
-- Run All as ACCOUNTADMIN. Contains no secret.
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS ACT_READER;
CREATE WAREHOUSE IF NOT EXISTS ACT_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60;
GRANT USAGE ON WAREHOUSE ACT_WH TO ROLE ACT_READER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ACT_READER;
GRANT DATABASE ROLE SNOWFLAKE.USAGE_VIEWER TO ROLE ACT_READER;
GRANT DATABASE ROLE SNOWFLAKE.SECURITY_VIEWER TO ROLE ACT_READER;
CREATE OR REPLACE USER ACT_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = ACT_READER
  DEFAULT_WAREHOUSE = ACT_WH
  WORKLOAD_IDENTITY = (
    TYPE = OIDC
    ISSUER = '{{ISSUER}}'
    SUBJECT = '{{SUBJECT}}'
    OIDC_AUDIENCE_LIST = ('{{AUDIENCE}}')
  );
GRANT ROLE ACT_READER TO USER ACT_SVC;
-- Last result row: the "Finish in ACT" link (setup token {{STATE}}).
SELECT '{{RETURN_URL}}&account=' || CURRENT_ORGANIZATION_NAME() || '-' || CURRENT_ACCOUNT_NAME() AS "Finish in ACT";
